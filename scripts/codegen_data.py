#!/usr/bin/env python3
"""
Generate Rust registry, packet, and block-state tables in `crates/mc-data/src/generated/`
from Mojang's official `reference/generated/reports/{packets,registries,blocks}.json`.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPORTS = ROOT / "reference" / "generated" / "reports"
OUT_DIR = ROOT / "crates" / "mc-data" / "src" / "generated"


def gen_packets() -> None:
    pkts = json.loads((REPORTS / "packets.json").read_text(encoding="utf-8"))
    proto_map = {
        "handshake": "ConnectionProtocol::Handshake",
        "status": "ConnectionProtocol::Status",
        "login": "ConnectionProtocol::Login",
        "configuration": "ConnectionProtocol::Configuration",
        "play": "ConnectionProtocol::Play",
    }
    dir_map = {
        "clientbound": "PacketDirection::Clientbound",
        "serverbound": "PacketDirection::Serverbound",
    }

    rows = []
    for proto, dirs in sorted(pkts.items()):
        for d, entries in sorted(dirs.items()):
            for name, meta in sorted(entries.items(), key=lambda kv: kv[1]["protocol_id"]):
                rows.append((proto_map[proto], dir_map[d], meta["protocol_id"], name))

    lines = [
        "// @generated by scripts/codegen_data.py from reference/generated/reports/packets.json",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]",
        "pub enum ConnectionProtocol {",
        "    Handshake,",
        "    Status,",
        "    Login,",
        "    Configuration,",
        "    Play,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]",
        "pub enum PacketDirection {",
        "    Clientbound,",
        "    Serverbound,",
        "}",
        "",
        "pub const PACKETS: &[(ConnectionProtocol, PacketDirection, u32, &str)] = &[",
    ]
    for p, d, pid, name in rows:
        lines.append(f'    ({p}, {d}, {pid}, "{name}"),')
    lines.extend([
        "];",
        "",
        "// JAVA: net.minecraft.network.protocol.PacketType",
        "pub fn packet_id(proto: ConnectionProtocol, dir: PacketDirection, name: &str) -> Option<u32> {",
        "    PACKETS.iter().find(|(p, d, _, n)| *p == proto && *d == dir && *n == name).map(|(_, _, id, _)| *id)",
        "}",
        "",
        "pub fn packet_name(proto: ConnectionProtocol, dir: PacketDirection, id: u32) -> Option<&'static str> {",
        "    PACKETS.iter().find(|(p, d, pid, _)| *p == proto && *d == dir && *pid == id).map(|(_, _, _, n)| *n)",
        "}",
        "",
    ])
    (OUT_DIR / "packets.rs").write_text("\n".join(lines), encoding="utf-8")
    print(f"[codegen] packets.rs: {len(rows)} packet definitions")


def gen_registries() -> None:
    regs = json.loads((REPORTS / "registries.json").read_text(encoding="utf-8"))
    lines = [
        "// @generated by scripts/codegen_data.py from reference/generated/reports/registries.json",
        "",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct RegistryInfo {",
        "    pub id: &'static str,",
        "    pub protocol_id: i32,",
        "    pub entries: &'static [(&'static str, i32)],",
        "}",
        "",
        "impl RegistryInfo {",
        "    // JAVA: net.minecraft.core.IdMap#getId",
        "    pub fn get_id(&self, name: &str) -> Option<i32> {",
        "        self.entries.iter().find(|(n, _)| *n == name).map(|(_, id)| *id)",
        "    }",
        "",
        "    // JAVA: net.minecraft.core.IdMap#byId",
        "    pub fn by_id(&self, id: i32) -> Option<&'static str> {",
        "        self.entries.iter().find(|(_, eid)| *eid == id).map(|(n, _)| *n)",
        "    }",
        "}",
        "",
    ]

    reg_consts = []
    for idx, (reg_name, reg_obj) in enumerate(sorted(regs.items(), key=lambda kv: kv[1].get("protocol_id", 99999))):
        cname = f"REG_{idx}"
        entries = sorted(reg_obj["entries"].items(), key=lambda kv: kv[1]["protocol_id"])
        lines.append(f"const {cname}: &[(&str, i32)] = &[")
        for ename, emeta in entries:
            lines.append(f'    ("{ename}", {emeta["protocol_id"]}),')
        lines.append("];")
        reg_consts.append((reg_name, reg_obj.get("protocol_id", -1), cname))

    lines.append("")
    lines.append("pub const REGISTRIES: &[RegistryInfo] = &[")
    for rname, pid, cname in reg_consts:
        lines.append(f'    RegistryInfo {{ id: "{rname}", protocol_id: {pid}, entries: {cname} }},')
    lines.extend([
        "];",
        "",
        "// JAVA: net.minecraft.core.registries.BuiltInRegistries",
        "pub fn get_registry(id: &str) -> Option<&'static RegistryInfo> {",
        "    REGISTRIES.iter().find(|r| r.id == id)",
        "}",
        "",
    ])
    (OUT_DIR / "registries.rs").write_text("\n".join(lines), encoding="utf-8")
    print(f"[codegen] registries.rs: {len(reg_consts)} registries")


def gen_blocks() -> None:
    blks = json.loads((REPORTS / "blocks.json").read_text(encoding="utf-8"))
    block_defs = []
    max_state_id = 0
    for bname, binfo in sorted(blks.items()):
        states = binfo["states"]
        first_id = min(s["id"] for s in states)
        default_id = next((s["id"] for s in states if s.get("default")), first_id)
        max_state_id = max(max_state_id, *(s["id"] for s in states))
        block_defs.append((bname, default_id, first_id, len(states), states))

    state_to_block = [0] * (max_state_id + 1)
    state_props = [""] * (max_state_id + 1)
    for bidx, (bname, default_id, first_id, count, states) in enumerate(block_defs):
        for s in states:
            sid = s["id"]
            state_to_block[sid] = bidx
            props = s.get("properties") or {}
            state_props[sid] = ",".join(f"{k}={v}" for k, v in sorted(props.items()))

    lines = [
        "// @generated by scripts/codegen_data.py from reference/generated/reports/blocks.json",
        "",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct BlockDef {",
        "    pub id: &'static str,",
        "    pub default_state_id: u32,",
        "    pub first_state_id: u32,",
        "    pub state_count: u16,",
        "}",
        "",
        f"pub const TOTAL_BLOCK_STATES: usize = {max_state_id + 1};",
        "",
        "pub const BLOCKS: &[BlockDef] = &[",
    ]
    for bname, def_id, first_id, cnt, _ in block_defs:
        lines.append(
            f'    BlockDef {{ id: "{bname}", default_state_id: {def_id}, first_state_id: {first_id}, state_count: {cnt} }},'
        )
    lines.append("];")
    lines.append("")
    lines.append("pub const STATE_TO_BLOCK: &[u16] = &[")
    for i in range(0, len(state_to_block), 16):
        lines.append("    " + ", ".join(str(x) for x in state_to_block[i : i + 16]) + ",")
    lines.append("];")
    lines.append("")
    lines.append("pub const STATE_PROPERTIES: &[&str] = &[")
    for p in state_props:
        lines.append(f'    "{p}",')
    lines.extend([
        "];",
        "",
        "// JAVA: net.minecraft.world.level.block.Block#getId",
        "pub fn block_by_name(name: &str) -> Option<&'static BlockDef> {",
        "    BLOCKS.binary_search_by(|b| b.id.cmp(name)).ok().map(|idx| &BLOCKS[idx])",
        "}",
        "",
        "// JAVA: net.minecraft.world.level.block.Block#stateById",
        "pub fn block_for_state(state_id: u32) -> Option<&'static BlockDef> {",
        "    STATE_TO_BLOCK.get(state_id as usize).map(|&bidx| &BLOCKS[bidx as usize])",
        "}",
        "",
        "pub fn state_properties(state_id: u32) -> Option<&'static str> {",
        "    STATE_PROPERTIES.get(state_id as usize).copied()",
        "}",
        "",
    ])
    (OUT_DIR / "blocks.rs").write_text("\n".join(lines), encoding="utf-8")
    print(f"[codegen] blocks.rs: {len(block_defs)} blocks, {max_state_id + 1} states")


def main() -> int:
    if not (REPORTS / "packets.json").exists():
        raise FileNotFoundError(f"Missing {REPORTS / 'packets.json'}; run scripts/fetch_reference.py first")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    gen_packets()
    gen_registries()
    gen_blocks()
    (OUT_DIR / "mod.rs").write_text(
        "pub mod blocks;\npub mod packets;\npub mod registries;\n",
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
